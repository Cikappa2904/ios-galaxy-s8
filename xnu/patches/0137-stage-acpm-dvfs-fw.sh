#!/bin/bash
# dxb runs patches/*.sh from the XNU source root before applying *.patch.
#
# Patch 0127 (s8_cpufreq.c) loads Samsung's ACPM DVFS plugin into APM SRAM
# when bsd/dev/s8_acpm_dvfs_fw.h exists; without it the CPUs stay at the
# S-Boot clocks (A53 1053 MHz, Mongoose 1066 MHz). The plugin is a Samsung
# binary, so it is not kept in this repository: it is fetched at build time
# from Samsung's GPL kernel source for the Exynos 8895 (universal8895,
# firmware/exynos8895_acpm_dvfs.fw.ihex), at a fixed commit and checksum.
set -euo pipefail

case "${MACHINE_CONFIG:-}" in
    A5XELTE) ;;
    *) exit 0 ;;
esac
[[ -f bsd/dev/s8_acpm_dvfs_fw.h ]] && exit 0

repo=ivanmeler/android_kernel_samsung_universal8895
sha=5dece0de832eb8b89b79246c83f386ef6f35522f
want=8eb0e05a4869c287f90891e277754ce1420f3414585ee5c1630320e9f5a1b1e4
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL --retry 3 -o "$tmp/fw.ihex" \
    "https://raw.githubusercontent.com/$repo/$sha/firmware/exynos8895_acpm_dvfs.fw.ihex"
got=$(shasum -a 256 "$tmp/fw.ihex" | cut -d' ' -f1)
if [[ "$got" != "$want" ]]; then
    echo "acpm dvfs firmware: sha256 $got, expected $want" >&2
    exit 1
fi

python3 - "$tmp/fw.ihex" bsd/dev/s8_acpm_dvfs_fw.h <<'PY'
import sys
data = bytearray()
base = 0
for line in open(sys.argv[1]):
    line = line.strip()
    if not line.startswith(':'):
        continue
    rec = bytes.fromhex(line[1:])
    n, addr, kind = rec[0], (rec[1] << 8) | rec[2], rec[3]
    if (sum(rec) & 0xff) != 0:
        raise SystemExit('ihex checksum error')
    if kind == 0:
        off = base + addr
        if len(data) < off:
            data.extend(b'\0' * (off - len(data)))
        data[off:off + n] = rec[4:4 + n]
    elif kind == 1:
        break
    elif kind == 2:
        base = ((rec[4] << 8) | rec[5]) << 4
    elif kind == 4:
        base = ((rec[4] << 8) | rec[5]) << 16
with open(sys.argv[2], 'w') as f:
    f.write('/* Generated by 0137-stage-acpm-dvfs-fw.sh from Samsung\'s\n'
            ' * exynos8895_acpm_dvfs.fw.ihex (%d bytes). Not in the repository. */\n' % len(data))
    f.write('static const uint8_t s8_acpm_dvfs_fw[%d] = {\n' % len(data))
    for i in range(0, len(data), 16):
        f.write('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
print('s8_acpm_dvfs_fw.h: %d bytes' % len(data))
PY
