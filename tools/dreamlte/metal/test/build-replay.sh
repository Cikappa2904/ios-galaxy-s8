#!/bin/bash
# Build and run the Mali replay generator (test/replay-gen.c) and write the
# loader's replay table tools/dreamlte/s8_mali_replay.h. Same inputs as
# build-draw-test.sh (whose test shader cache it builds first).
#   build-replay.sh MESA_SRC MESA_BUILD AIR2NIR OUTDIR
set -euo pipefail
src=$(realpath "$1"); bld=$(realpath "$2"); air2nir=$(realpath "$3"); out=$(realpath -m "$4")
here=$(cd "$(dirname "$0")" && pwd)
bash "$here/build-draw-test.sh" "$src" "$bld" "$air2nir" "$out" > "$out.draw-test.txt" 2>&1 \
	|| { cat "$out.draw-test.txt"; exit 1; }
flags=$(python3 - "$bld" <<'PY'
import json, shlex, sys, os
bld = sys.argv[1]
for e in json.load(open(os.path.join(bld, 'compile_commands.json'))):
    if e['file'].endswith('panfrost/lib/pan_desc.c') and 'arch-v6' in e['command']:
        out, skip = [], False
        for a in shlex.split(e['command'])[1:]:
            if skip:
                skip = False
                continue
            if a in ('-o', '-MF', '-MQ', '-c'):
                skip = True
                continue
            if a == '-MD' or a.endswith('.c') or a.startswith('-W'):
                continue
            if a.startswith('-I') and not os.path.isabs(a[2:]):
                a = '-I' + os.path.normpath(os.path.join(bld, a[2:]))
            out.append(a)
        print(' '.join(shlex.quote(a) for a in out))
        break
PY
)
libs=$(cd "$bld" && find src -name '*.a' | grep -E 'panfrost|pan-|pandecode|libnir|mesa_util|blake3|compiler|c11|libpankmod|midgard|valhall' | sed "s#^#$bld/#")
eval cc $flags -DS8_TEST -I"$src/src/panfrost/lib" -I"$here/.." -idirafter "$here/../../ios/stub" -Wall -Wno-unused-parameter -g \
	'"$here/replay-gen.c"' '"$here/../s8mtl_draw.c"' -Wl,--start-group $libs -Wl,--end-group \
	-lm -lpthread -lz -ldl -lexpat -ldrm -fopenmp -o '"$out/replay-gen"'
# S8_RP_CACHE / S8_RP_LIST: another cache and a probe list (probes.py)
"$out/replay-gen" "${S8_RP_CACHE:-$out/test.s8sc}" "$out/replay.bin" ${S8_RP_LIST:+"$S8_RP_LIST"} \
	> "$out/replay-gen.log" 2>&1 && rc=0 || rc=$?
grep -E '^(====|S8 MALI)' "$out/replay-gen.log"
[ $rc = 0 ] || { echo "replay-gen failed ($rc), log $out/replay-gen.log"; exit $rc; }
hdr=$here/../../s8_mali_replay.h
{
	echo "/* Generated by tools/dreamlte/metal/test/build-replay.sh (replay-gen.c): do not edit. */"
	echo "#define S8_REPLAY_SIZE $(stat -c %s "$out/replay.bin")u"
	echo 'static const unsigned char s8_replay[] __attribute__((aligned(16), section(".replay"))) = {'
	xxd -i < "$out/replay.bin"
	echo "};"
} > "$hdr"
ls -l "$out/replay.bin" "$hdr"
sha256sum "$out/replay.bin"
