#!/usr/bin/env python3
"""Loader replay table (tools/dreamlte/s8_mali_replay.h) from a phone dump.

undump.py rebuilt the GPU memory behind iOS's first failed vertex/tiler
chain (MEM.bin at BASE). This writes the same record format as
replay-gen.c ('B' base, 'P' page, 'S' submit, 'E' end), replaying that
chain on the GPU before XNU starts, cut into variants:
  each VERTEX job alone; the first one with a 16 MiB thread storage area
  (TLS sizing); the first TILER job alone; the whole chain, also with the
  big thread storage area.

  dump2replay.py MEM.bin BASE JC TLS_DESC OUT.h
"""
import struct, sys

BIG_TLS = 0x8c4000000           # 16 MiB, zeroed by the loader (inside the replay range)
BIG_TLS_SIZE = 16 << 20
TILER_HEAP = 0x8c1000000        # S8GPU_HEAP_PA: the replay range starts here
MAXJOBS = 8


def main():
    mem_path, base, jc, tls_desc, out = sys.argv[1], int(sys.argv[2], 0), int(sys.argv[3], 0), \
        int(sys.argv[4], 0), sys.argv[5]
    mem = bytearray(open(mem_path, 'rb').read())
    lo = TILER_HEAP
    hi = BIG_TLS + BIG_TLS_SIZE
    assert lo <= base and base + len(mem) <= hi

    def q(a):
        return struct.unpack_from('<Q', mem, a - base)[0]

    def setq(a, v):
        struct.pack_into('<Q', mem, a - base, v)

    def d(a):
        return struct.unpack_from('<I', mem, a - base)[0]

    def setd(a, v):
        struct.pack_into('<I', mem, a - base, v)

    chain = []
    j = jc
    while j and len(chain) < 64:
        chain.append(j)
        j = q(j + 0x18)
    types = {a: (d(a + 0x10) >> 1) & 0x7f for a in chain}
    print('chain:', ' '.join(f'0x{a:x}(t{types[a]})' for a in chain))
    tls_base = q(tls_desc + 8)
    print(f'TLS desc 0x{tls_desc:x}: size field {d(tls_desc) & 31}, base 0x{tls_base:x}')
    assert tls_base != 0

    rec = bytearray()
    rec += struct.pack('<IIQ', ord('B'), 0, lo)
    pages = [o for o in range(0, len(mem), 4096) if any(mem[o:o + 4096])]

    def put_pages(sel):
        nonlocal rec
        for o in sel:
            page = bytes(mem[o:o + 4096]).ljust(4096, b'\0')
            rec += struct.pack('<IIQ', ord('P'), 0, base + o) + page

    def page_of(a):
        return (a - base) & ~4095

    put_pages(pages)                       # everything once
    nsub = 0

    def submit(head, label, patches=()):
        """patches: (addr, kind, value); job/TLS pages rewritten around it."""
        nonlocal rec, nsub
        saved = []
        for a, kind, v in patches:
            saved.append((a, kind, q(a) if kind == 'q' else d(a)))
            (setq if kind == 'q' else setd)(a, v)
        jobs = []
        h = head
        while h and len(jobs) < MAXJOBS:
            jobs.append(h)
            h = q(h + 0x18)
        touched = sorted({page_of(a) for a in jobs} | {page_of(a) for a, _, _ in patches} | {page_of(tls_desc)})
        put_pages(touched)
        rec += struct.pack('<IIQQII', ord('S'), 1, head, 0, len(jobs), 0)
        rec += b''.join(struct.pack('<Q', a) for a in jobs).ljust(64, b'\0')
        rec += label.encode()[:31].ljust(32, b'\0')
        for a, kind, v in saved:
            (setq if kind == 'q' else setd)(a, v)
        put_pages(sorted({page_of(a) for a, _, _ in patches}))
        nsub += 1
        print(f'record {nsub}: {label}: head 0x{head:x}, {len(jobs)} jobs')

    vertex = [a for a in chain if types[a] == 5]
    tiler = [a for a in chain if types[a] == 7]
    for i, v in enumerate(vertex):
        submit(v, f'iOS vertex {i} alone', [(v + 0x18, 'q', 0)])
    submit(vertex[0], 'iOS vertex 0, 16M TLS', [(vertex[0] + 0x18, 'q', 0), (tls_desc + 8, 'q', BIG_TLS)])
    submit(tiler[0], 'iOS tiler 0 alone', [(tiler[0] + 0x14, 'd', 0), (tiler[0] + 0x18, 'q', 0)])
    submit(jc, 'iOS chain')
    submit(jc, 'iOS chain, 16M TLS', [(tls_desc + 8, 'q', BIG_TLS)])
    rec += struct.pack('<IIQ', ord('E'), 0, hi - lo)
    with open(out, 'w') as f:
        f.write('/* Generated by tools/dreamlte/metal/test/dump2replay.py from a phone dump: do not edit. */\n')
        f.write(f'#define S8_REPLAY_SIZE {len(rec)}u\n')
        f.write('static const unsigned char s8_replay[] __attribute__((aligned(16), section(".replay"))) = {\n')
        for o in range(0, len(rec), 16):
            f.write(' ' + ', '.join(f'0x{b:02x}' for b in rec[o:o + 16]) + ',\n')
        f.write('};\n')
    print(f'{out}: {len(rec)} bytes, {len(pages)} pages, {nsub} submits, range 0x{lo:x}+0x{hi - lo:x}')


if __name__ == '__main__':
    main()
